function getInitialLang() {
  if (typeof window === 'undefined') return 'ru'
  const saved = localStorage.getItem(STORAGE_KEY)
  const legacySaved = localStorage.getItem('language')
  if (saved === 'ru' || saved === 'en' || saved === 'kz') return saved
  if (legacySaved === 'ru' || legacySaved === 'en' || legacySaved === 'kz' || legacySaved === 'kk') {
    return legacySaved === 'kk' ? 'kz' : legacySaved
  }
  const nav = (navigator.language || '').toLowerCase()
  if (nav.startsWith('kk') || nav.startsWith('kz')) return 'kz'
  if (nav.startsWith('en')) return 'en'
  return 'ru'
}

export function setLang(lang) {
  const next = lang === 'ru' || lang === 'en' || lang === 'kz' ? lang : 'ru'
  i18n.changeLanguage(next)
  try {
    localStorage.setItem(STORAGE_KEY, next)
    localStorage.setItem('language', next)
  } catch {
    /* ignore */
  }
}

i18n.use(initReactI18next).init({
  resources,
  lng: getInitialLang(),
  fallbackLng: 'ru',
  interpolation: { escapeValue: false },
})

export default i18n

